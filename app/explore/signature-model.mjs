  const follow = traits.find(item => item.key === 'follow').score;
  const switchScore = lead !== null && follow !== null ? Math.min(lead,follow) : null;
  traits.push({id:'trait-switch',key:'switch',label:'Switch',score:switchScore,kind:'trait',meaning:'Dominer et se soumettre te font tous les deux kiffer. Le score reprend le plus faible des deux indices.'});
